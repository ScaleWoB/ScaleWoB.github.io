export const interpolate = (
  template: string,
  values: Record<string, string | number> = {}
) => {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : ''
  );
};
